ITEM_NAME_EXTRACT_SYSTEM_PROMPT = "你是一个专业的旅游助手，擅长理解用户意图并提取景点、线路、酒店、餐厅或地区等关键信息。"

ITEM_NAME_EXTRACT_TEMPLATE = """
历史会话：
{history_text}

当前用户问题：
{query}

请根据历史会话和当前问题，提取用户正在询问的旅游实体名称（item_names）。
实体可以是：景点名称、线路名称、酒店名称、餐厅名称，商圈/地标，或地区/城市名称。
1. 如果用户明确提到了上述实体，请提取出来。可能有一个或多个，但不能重复。
2. 优先提取更具体的名称（如“春熙路”“宽窄巷子”），地区名（如“成都”）可同时保留。
3. 如果用户使用了代词（如"这个"、"那里"、"它"），请结合历史会话指代消解，确定实体名称。
4. 如果问题较宽泛（如"成都怎么玩""成都有哪些必去景点"），提取地区名即可，不要因为不够具体就返回空列表。
5. 请重新改写用户的问题（rewritten_query），使其成为包含关键实体/地区的独立完整问题。

请直接返回JSON格式结果，格式如下：
{{
    "item_names": ["春熙路", "成都"],
    "rewritten_query": "成都春熙路附近有哪些美食推荐"
}}
"""
